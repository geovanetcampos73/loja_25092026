    private Connection getConnection() throws SQLException {
        return DriverManager.getConnection(URL, USUARIO, SENHA);
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0); // Limpa a tabela
        String sql = "SELECT codigo, login,senha  FROM login"; // Não trazemos a senha por segurança

        try (Connection con = getConnection();
             PreparedStatement stmt = con.prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {
                modeloTabela.addRow(new Object[]{
                    rs.getInt("codigo"),
                    rs.getString("login"),
                    rs.getString("senha"),
                    
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar dados: " + e.getMessage());
        }
    }

    private void salvarUsuario() {
        String login = txtLogin.getText().trim();
        String senha = new String(txtSenha.getPassword()).trim();
        String idStr = txtId.getText();
        if (login.isEmpty() || senha.isEmpty()) {
          JOptionPane.showMessageDialog(this, "Login e Senha são obrigatórios!");
            return;
        }

        try (Connection con = getConnection()) {
            if (operacao.equals("I")) {
                // INSERT (Novo Registro)
                String sql = "INSERT INTO login (login, senha) VALUES (?, ?)";
                try (PreparedStatement stmt = con.prepareStatement(sql)) {
                    stmt.setString(1, login);
                    stmt.setString(2, senha);
                    stmt.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Usuário cadastrado com sucesso!");
                }
            } else {
                // UPDATE (Atualizar Registro Existente)
                String sql = "UPDATE login SET login = ?, senha = ? WHERE codigo = ?";
                try (PreparedStatement stmt = con.prepareStatement(sql)) {
                    stmt.setString(1, login);
                    stmt.setString(2, senha);
                    stmt.setInt(3, Integer.parseInt(idStr));
                    stmt.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Usuário atualizado com sucesso!");
                }
            }
            limparCampos();
            carregarTabela();
            tab_usuarios.setSelectedIndex(0); // Volta para o Grid
            tab_usuarios.setEnabledAt(1, false);
            tab_usuarios.setEnabledAt(0, true);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar usuário: " + e.getMessage());
        }
    }

    private void prepararEdicao() {
        int linhaSelecionada = jTableUsuarios.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um usuário na tabela para editar.");
            return;
        }

        String id = jTableUsuarios.getValueAt(linhaSelecionada, 0).toString();
        
        // Busca os dados completos do usuário no banco, incluindo a senha para edição
        String sql = "SELECT login, senha FROM login WHERE codigo = ?";
        try (Connection con = getConnection();
             PreparedStatement stmt = con.prepareStatement(sql)) {
            
            stmt.setInt(1, Integer.parseInt(id));
            try (ResultSet rs = stmt.executeQuery()) {
                if (rs.next()) {
                    txtLogin.setText(rs.getString("login"));
                    txtSenha.setText(rs.getString("senha"));
                    txtId.setText(id);   
                    tab_usuarios.setEnabledAt(1, true);
                    tab_usuarios.setSelectedIndex(1); // Vai para a aba de cadastro
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao buscar usuário: " + e.getMessage());
        }
    }

    private void excluirUsuario() {
        int linhaSelecionada = jTableUsuarios.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um usuário na tabela para excluir.");
            return;
        }

        int id = (int) jTableUsuarios.getValueAt(linhaSelecionada, 0);
        String loginSelecionado = (String) jTableUsuarios.getValueAt(linhaSelecionada, 1);

        int confirmacao = JOptionPane.showConfirmDialog(this, 
                "Tem certeza que deseja excluir o usuário: " + loginSelecionado + "?", 
                "Confirmação", JOptionPane.YES_NO_OPTION);

        if (confirmacao == JOptionPane.YES_OPTION) {
            String sql = "DELETE FROM login WHERE codigo = ?";
            try (Connection con = getConnection();
                 PreparedStatement stmt = con.prepareStatement(sql)) {
                
                stmt.setInt(1, id);
                stmt.executeUpdate();
                JOptionPane.showMessageDialog(this, "Usuário excluído com sucesso!");
                carregarTabela(); // Atualiza o grid
                
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Erro ao excluir usuário: " + e.getMessage());
            }
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtLogin.setText("");
        txtSenha.setText("");
    }

